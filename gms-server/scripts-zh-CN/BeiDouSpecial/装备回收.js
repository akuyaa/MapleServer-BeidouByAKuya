function start() {
    levelStart();
}

/* 入口：只扫描装备栏 */
function levelStart() {
    sel = 1; // 装备栏
    text = "开始扫描#e装备栏#n中的可回收装备……\r\n\r\n";
    let hasVal = false;
    for (let i = 0; i < 96; i++) {
        let item = cm.getInventory(sel).getItem(i);
        if (item && ALLOW_LIST.has(item.getItemId())) {
            hasVal = true;
            text += "#L" + item.getPosition() + "##t" + item.getItemId() +
                    "##i" + item.getItemId() + "##l\r\n";
        }
    }
    if (!hasVal) {
        cm.sendOk("装备栏暂无可回收的指定装备！");
        cm.dispose();
        return;
    }
    cm.sendNextSelectLevel("DoRemove", text);
}

/* 单件兑换：删除 → 发放黄金枫叶 → 强制写包 */
function levelDoRemove(choose) {
    let item = cm.getInventory(sel).getItem(choose);
    if (!item) {
        cm.sendOk("该位置道具不存在！");
        cm.dispose();
        return;
    }
    let itemId = item.getItemId();
    let reward = ALLOW_LIST.get(itemId);
    if (!reward) {
        cm.sendOk("该装备不在回收列表中，无法兑换！");
        cm.dispose();
        return;
    }

    /* 1. 删除装备 */
    cm.removeAllByInventorySlot(sel, choose);

    /* 2. 给黄金枫叶（4000313） */
    cm.gainItem(4000313, reward);

    /* 3. 关键：立即把“获得物品”写包到客户端 */
    let c = cm.getPlayer().getClient();
    if (c != null) {
        // 通知客户端更新背包（InventoryPacket）
        c.getSession().write(Packages.tools.packet.CWvsContext.inventoryOperation(true, false));
    }

    cm.sendOk("兑换成功！#t" + itemId + "# 已删除，你获得了 #b" + reward + "#k 个黄金枫叶！");
    cm.dispose();
}